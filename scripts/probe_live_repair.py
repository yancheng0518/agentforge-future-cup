"""Synthetic defect -> actual Docker failure -> live fixer -> actual Docker retest.

This independent experiment never alters an existing workflow, executes a
candidate on the host, or applies changes to examples/todo. It demonstrates
repair of a declared fixture, NOT a naturally occurring model development bug.
"""
from __future__ import annotations

import argparse
import asyncio
from copy import deepcopy
from datetime import datetime, timezone
import difflib
import hashlib
import json
from pathlib import Path
import re
import sys
import time
from uuid import uuid4

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
sys.path.insert(0, str(ROOT / "scripts"))
from agentforge.definitions import AGENTS
from agentforge.runtime import MOCK_SOURCE, Runtime, RuntimeErrorSafe
from run_live_demo import redact

REQUIREMENT = "增加任务完成状态，并支持按照完成状态筛选任务。"
SEED = MOCK_SOURCE.replace("{filter}", "").replace(
    "Candidate generated by the explicit deterministic mock adapter.",
    "Synthetic missing-filter fixture; not generated by a live model.")


def sha(source):
    return hashlib.sha256(source.encode("utf-8")).hexdigest()


def now():
    return datetime.now(timezone.utc).isoformat()


def suite_result(result, passed):
    """Require the trusted runner's completed ten-test suite, not startup errors."""
    return (result.get("isolated") is True
            and result.get("status") == ("passed" if passed else "failed")
            and type(result.get("exit_code")) is int
            and result["exit_code"] == (0 if passed else 1)
            and ('AGENTFORGE_ACCEPTANCE={"tests": 10, "passed": '
                 + str(passed).lower() + '}') in result.get("stdout", "")
            and re.search(r"Ran 10 tests? in ", result.get("stderr", "")) is not None)


def expected_seed_failure(result):
    stderr = result.get("stderr", "")
    return (suite_result(result, False)
            and "FAIL: test_filter_completed " in stderr
            and "FAIL: test_filter_incomplete " in stderr
            and "FAILED (failures=2)" in stderr)


def assess(evidence):
    seed = evidence.get("seed", {})
    chain = seed.get("sha256") == sha(SEED) and expected_seed_failure(seed.get("test", {}))
    previous_hash, previous_test = seed.get("sha256"), seed.get("test", {})
    repaired = False
    for number, item in enumerate(evidence.get("rounds", []), 1):
        result = item.get("model_result", {})
        files = result.get("output", {}).get("files", [])
        candidate_hash = sha(files[0]["content"]) if (len(files) == 1 and files[0].get("path") == "todo.py"
                                                     and isinstance(files[0].get("content"), str)) else None
        chain = bool(chain and number <= 2 and item.get("round") == number
                     and suite_result(previous_test, False)
                     and item.get("input_sha256") == previous_hash
                     and item.get("feedback_test") == previous_test
                     and item.get("agent", {}).get("id") == "fixer"
                     and result.get("model_mode") == "live" and result.get("model_calls", 0) > 0
                     and candidate_hash and item.get("output_sha256") == candidate_hash
                     and item.get("acceptance_unchanged") is True
                     and item.get("candidate_unchanged_during_test") is True)
        previous_hash, previous_test = item.get("output_sha256"), item.get("test", {})
        repaired = bool(chain and previous_hash != seed.get("sha256") and suite_result(previous_test, True))
    review = evidence.get("review", {})
    review_passed = bool(review.get("candidate_sha256") == previous_hash
                         and review.get("model_result", {}).get("model_mode") == "live"
                         and review.get("model_result", {}).get("model_calls", 0) > 0
                         and review.get("model_result", {}).get("output", {}).get("passed") is True)
    return {"synthetic_seed_failure_verified": expected_seed_failure(seed.get("test", {})),
            "live_fix_of_synthetic_defect_verified": repaired,
            "live_review_passed": review_passed,
            "passed": repaired and (not evidence.get("review_requested") or review_passed),
            "natural_model_development_failure": False,
            "original_workflow_self_correction": False,
            "label": "Declared synthetic defect repaired by a real model; independent Docker validation."}


def acceptance_manifest(root):
    return {str(path.relative_to(root / "acceptance")).replace("\\", "/"): hashlib.sha256(path.read_bytes()).hexdigest()
            for path in sorted((root / "acceptance").rglob("*.py"))}


async def run_experiment(runtime, directory, max_repairs=2, review=False):
    if max_repairs not in (1, 2):
        raise ValueError("Only one or two repair rounds are supported")
    directory.mkdir(parents=True, exist_ok=True)
    output = directory / "evidence.json"
    run_id = "live-repair-" + uuid4().hex
    started = time.monotonic()
    evidence = {"experiment": "synthetic_seed_live_fixer_real_docker", "run_id": run_id,
                "started_at": now(), "model_mode": "live", "applied": False,
                "requirement": REQUIREMENT, "max_repairs": max_repairs, "review_requested": review,
                "seed": {"provenance": "Predeclared MOCK_SOURCE fixture with missing filter; not live-model output.",
                         "source_file": "seed.py.txt", "sha256": sha(SEED),
                         "expected_defect": "list(completed) ignores completed; both filter assertions fail."},
                "rounds": [], "model_calls": 0, "tokens": 0, "metrics_complete": True}

    def save():
        evidence["updated_at"] = now()
        evidence["duration_seconds"] = round(time.monotonic() - started, 2)
        evidence["outcome"] = assess(evidence)
        output.write_text(json.dumps(redact(evidence, runtime.settings.get("api_key", "")), ensure_ascii=False, indent=2), encoding="utf-8")

    async def invoke(agent, kind, context, record):
        record["agent"] = deepcopy(agent)
        record["model_started_at"] = now()
        save()
        try:
            result = await runtime.invoke(agent, {"mode": "live", "kind": kind, "requirement": REQUIREMENT,
                                                  "workflow_id": "independent_synthetic_repair_probe"}, deepcopy(context))
            record["model_result"] = result
        except Exception as exc:
            record["model_error"] = str(exc) if isinstance(exc, RuntimeErrorSafe) else type(exc).__name__
            result = {key: getattr(exc, key, default) for key, default in
                      (("model_calls", 0), ("tokens", 0), ("metrics_complete", False), ("tool_calls", []))}
            record["failed_model_metrics"] = result
            raise
        finally:
            record["model_finished_at"] = now()
            if "result" in locals():
                evidence["model_calls"] += result.get("model_calls", 0)
                evidence["tokens"] += result.get("tokens", 0)
                evidence["metrics_complete"] &= result.get("metrics_complete", False)
            save()
        return result

    try:
        health = await runtime.health()
        evidence["health_at_start"] = health
        if not health.get("sandbox", {}).get("available") or not health.get("model", {}).get("configured"):
            evidence["blocked"] = "Docker isolation and configured live model are both required. No model requested."
            return evidence
        manifest = acceptance_manifest(runtime.root)
        evidence["acceptance_manifest"] = manifest
        evidence["prepared"] = await runtime.prepare(run_id)
        (directory / "seed.py.txt").write_text(SEED, encoding="utf-8", newline="\n")
        await runtime.apply_candidate(run_id, [{"path": "todo.py", "content": SEED}])
        evidence["seed"]["test_started_at"] = now()
        seed_test = await runtime.test(run_id)
        evidence["seed"].update(test=seed_test, test_finished_at=now())
        save()
        if acceptance_manifest(runtime.root) != manifest or not expected_seed_failure(seed_test):
            evidence["blocked"] = "Seed did not reproduce the declared two assertion failures with unchanged acceptance. No model requested."
            return evidence
        previous_test = seed_test
        fixer = deepcopy(next(agent for agent in AGENTS if agent["id"] == "fixer"))
        for number in range(1, max_repairs + 1):
            project = await runtime.read_project(run_id)
            before = project["files"][0]["content"]
            item = {"round": number, "input_sha256": sha(before), "feedback_test": deepcopy(previous_test)}
            evidence["rounds"].append(item)
            context = {"run_id": run_id, "attempt": number, "requirement": REQUIREMENT,
                       "experiment_provenance": evidence["seed"]["provenance"], "project": project,
                       "retrieval": await runtime.retrieve(REQUIREMENT), "diff": await runtime.diff(run_id),
                       "test": previous_test, "feedback": {"test": previous_test, "next_attempt": number}}
            result = await invoke(fixer, "fix", context, item)
            if result.get("model_mode") != "live" or result.get("model_calls", 0) < 1:
                raise RuntimeErrorSafe("A live fixer response is required; mock fallback is forbidden.")
            await runtime.apply_candidate(run_id, result["output"]["files"])
            after = (await runtime.read_project(run_id))["files"][0]["content"]
            item["output_sha256"] = sha(after)
            item["repair_diff"] = "".join(difflib.unified_diff(before.splitlines(True), after.splitlines(True), fromfile="before/todo.py", tofile="after/todo.py"))
            (directory / f"round-{number}.py.txt").write_text(redact(after, runtime.settings.get("api_key", "")), encoding="utf-8", newline="\n")
            save()
            item["test_started_at"] = now()
            item["test"] = await runtime.test(run_id)
            item["test_finished_at"] = now()
            item["acceptance_unchanged"] = acceptance_manifest(runtime.root) == manifest
            item["candidate_unchanged_during_test"] = sha((await runtime.read_project(run_id))["files"][0]["content"]) == sha(after)
            save()
            if not item["acceptance_unchanged"] or not item["candidate_unchanged_during_test"]:
                raise RuntimeErrorSafe("Candidate or acceptance changed while validating; evidence rejected.")
            previous_test = item["test"]
            if suite_result(previous_test, True):
                if review:
                    reviewer = deepcopy(next(agent for agent in AGENTS if agent["id"] == "reviewer"))
                    evidence["review"] = {"candidate_sha256": sha(after)}
                    context.update(project=await runtime.read_project(run_id), diff=await runtime.diff(run_id), test=previous_test,
                                   validation_scope={"id": f"probe-round-{number}", "candidate_hash": sha(after), "attempt": number})
                    await invoke(reviewer, "review", context, evidence["review"])
                break
            if not suite_result(previous_test, False):
                evidence["blocked"] = "Retest did not complete the independent suite; do not feed infrastructure failure into another repair."
                break
    except Exception as exc:
        evidence["error"] = str(exc) if isinstance(exc, RuntimeErrorSafe) else type(exc).__name__
    finally:
        save()
    return evidence


async def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--max-repairs", type=int, choices=(1, 2), default=2)
    parser.add_argument("--review", action="store_true", help="Request one live reviewer only after a passing Docker retest.")
    args = parser.parse_args(argv)
    directory = ROOT / ".agentforge" / "live-repair-probes" / (datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "-" + uuid4().hex[:6])
    runtime = Runtime(ROOT, directory)
    evidence = await run_experiment(runtime, directory, args.max_repairs, args.review)
    print(json.dumps({"evidence": str(directory / "evidence.json"), "run_id": evidence["run_id"],
                      "model_calls": evidence["model_calls"], "tokens": evidence["tokens"],
                      "metrics_complete": evidence["metrics_complete"], "outcome": evidence["outcome"],
                      "blocked": evidence.get("blocked"), "error": evidence.get("error")}, ensure_ascii=False, indent=2))
    return 0 if evidence["outcome"]["passed"] else 2


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
