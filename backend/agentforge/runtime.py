        allowed_tools = set(agent.get("tools", []))
        tools = [tool for tool in tools if tool["function"]["name"] in allowed_tools]
        traces, calls, tokens = metrics["tool_calls"], 0, 0
        for round_index in range(4):
            configured_model = agent.get("model")
            model = configured_model if configured_model and configured_model not in ("default", "mock", "inherit") else self.settings["model"]
            payload = {"model": model, "messages": messages, "temperature": 0.1, "max_tokens": 4096, "response_format": {"type": "json_object"}, "tools": tools, "tool_choice": "auto" if round_index < 2 and not metrics["contract_retries"] else "none"}
