def _user_env(name: str) -> str:
    if os.name != "nt":
        return ""
    try:
        import winreg
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment") as key:
            value, _ = winreg.QueryValueEx(key, name)
            return str(value)
    except (OSError, ImportError):
        return ""


def _settings(root: Path) -> dict:
    file_env = {}
    path = root / ".env"
    if path.is_file():
        for line in path.read_text(encoding="utf-8-sig").splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                key, value = line.split("=", 1)
                file_env[key.strip()] = value.strip().strip('"').strip("'")
    def get(name, default=""):
        return os.environ.get(name) or file_env.get(name) or default
    key = get("AGENTFORGE_LLM_API_KEY")
    source = "environment_or_dotenv" if key else "unconfigured"
    return {"api_key": key, "key_source": source,
            "base_url": get("AGENTFORGE_LLM_BASE_URL", "https://aigw.omniedu.com/v1").rstrip("/"),
            "model": get("AGENTFORGE_LLM_MODEL"),
            "timeout": min(120, max(5, int(get("AGENTFORGE_LLM_TIMEOUT", "60")))),
            "min_request_interval": min(60.0, max(0.0, float(get("AGENTFORGE_LLM_MIN_INTERVAL", "4.2")))),
            "docker_backend": get("AGENTFORGE_DOCKER_BACKEND", "native"),
            "wsl_distro": get("AGENTFORGE_WSL_DISTRO", "AgentForge"),
            "image": get("AGENTFORGE_TEST_IMAGE", "agentforge-test:py313")}


