class Runtime:
    def __init__(self, root: Path, data_dir: Path):
        self.root = Path(root).resolve()
        self.data_dir = Path(data_dir).resolve()
        self.settings = _settings(self.root)
        self._health_cache = None
        self._health_at = 0.0
        self._model_verified = False

    def snapshot_task(self, task_id="completion"):
        return snapshot_task(self.root, task_id)

    def model_config(self):
        return {"model": self.settings["model"], "base_url": self.settings["base_url"],
                "temperature": 0.1, "max_output_tokens": 4096, "tool_rounds": 4,
                "adapter_revision": 2, "contract_retries": 1, "automatic_tool_rounds": 2,
                "min_request_interval": self.settings.get("min_request_interval", 0.0),
                "timeout_seconds": self.settings["timeout"]}

    def _acceptance_manifest(self):
        return {str(path.relative_to(self.root / "acceptance")).replace("\\", "/"): hashlib.sha256(path.read_bytes()).hexdigest()
                for path in sorted((self.root / "acceptance").rglob("*.py"))}

    def _docker_command(self, *args):
        backend = self.settings.get("docker_backend", "native")
        if backend == "native":
            return ["docker", *args]
        if backend != "wsl":
            raise RuntimeErrorSafe("不支持的 Docker 后端；请选择 native 或 wsl。")
        distro = self.settings.get("wsl_distro", "AgentForge")
        if not re.fullmatch(r"[A-Za-z0-9_.-]{1,80}", distro):
            raise RuntimeErrorSafe("WSL 发行版名称格式无效。")
        return ["wsl", "--distribution", distro, "--user", "root", "--exec", "docker", *args]

    async def _mount_path(self, path):
        path = Path(path).resolve()
        if self.settings.get("docker_backend", "native") != "wsl":
            return str(path)
        prefix = self._docker_command()[:-1]
        code, out, _ = await self._command([*prefix, "wslpath", "-a", "-u", str(path)], timeout=15)
        value = out.strip()
        if code or not value.startswith("/") or "\n" in value or "," in value:
            raise RuntimeErrorSafe("无法将项目路径映射到 WSL；未运行候选代码。")
        return value

    def _run_dir(self, run_id):
        if not re.fullmatch(r"[A-Za-z0-9_-]{1,80}", str(run_id)):
            raise RuntimeErrorSafe("Invalid run identifier")
        path = self.data_dir / "runs" / run_id
        if path.is_symlink() or (path / "candidate").is_symlink():
            raise RuntimeErrorSafe("Symlink workspaces are not supported")
        resolved = path.resolve()
        if not resolved.is_relative_to(self.data_dir):
            raise RuntimeErrorSafe("Workspace escapes data directory")
        return resolved

    async def _command(self, args, timeout=8):
        """No shell, bounded output, kill-and-reap on timeout or cancellation."""
        proc = await asyncio.create_subprocess_exec(*args, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE)
        async def read(stream):
            chunks, size = [], 0
            while chunk := await stream.read(8192):
                size += len(chunk)
                if size > 131072:
                    raise RuntimeErrorSafe("Tool output exceeded 128 KiB")
                chunks.append(chunk)
            return b"".join(chunks).decode("utf-8", errors="replace")
        readers = [asyncio.create_task(read(proc.stdout)), asyncio.create_task(read(proc.stderr)), asyncio.create_task(proc.wait())]
        try:
            out, err, code = await asyncio.wait_for(asyncio.gather(*readers), timeout)
            return code, out, err
        except BaseException:
            if proc.returncode is None:
                proc.kill()
            await proc.wait()
            for task in readers:
                if not task.done():
                    task.cancel()
            await asyncio.gather(*readers, return_exceptions=True)
            raise

    async def health(self):
        now = time.monotonic()
        if self._health_cache and now - self._health_at < 5:
            return self._health_cache
        available, reason = False, "Docker CLI 未安装；自动验收测试已阻塞。"
        backend = self.settings.get("docker_backend", "native")
        executable = "wsl" if backend == "wsl" else "docker"
        if backend == "wsl":
            reason = "WSL 命令不可用；自动验收测试已阻塞。"
        if shutil.which(executable):
            try:
                code, out, _ = await self._command(self._docker_command("info", "--format", "{{.OSType}}"), timeout=15)
                if code or out.strip() != "linux":
                    reason = "WSL 内 Docker Linux 引擎不可用，请启动专用沙箱。" if backend == "wsl" else "Docker Linux 引擎不可用。"
                else:
                    code, _, _ = await self._command(self._docker_command("image", "inspect", self.settings["image"]))
                    available = code == 0
                    setup_script = "scripts/setup-wsl-sandbox.ps1" if backend == "wsl" else "scripts/setup-sandbox.ps1"
                    reason = "Docker 引擎与验收镜像可用；实际测试结果以容器运行记录为准。" if available else f"验收镜像缺失，请先运行 {setup_script}。"
            except (OSError, TimeoutError, RuntimeErrorSafe):
                reason = "Docker 预检失败或超时。"
        result = {"model": {"configured": bool(self.settings["api_key"] and self.settings["model"]), "model": self.settings["model"],
                            "base_url": self.settings["base_url"], "key_source": self.settings["key_source"],
                            "verified": self._model_verified, "config": self.model_config()},
                  "sandbox": {"available": available, "reason": reason, "image": self.settings["image"], "backend": backend,
                              "wsl_distro": self.settings.get("wsl_distro") if backend == "wsl" else None},
                  "mode": "mock"}
        self._health_at, self._health_cache = now, result
        return result

    async def prepare(self, run_id, task_snapshot=None):
        directory = self._run_dir(run_id)
        candidate = directory / "candidate"
        if (directory / "manifest.json").exists():
            manifest = json.loads((directory / "manifest.json").read_text(encoding="utf-8"))
            if task_snapshot and manifest.get("task_snapshot_sha256") != task_snapshot["snapshot_sha256"]:
                raise RuntimeErrorSafe("任务快照与已有工作区不一致，拒绝替换。")
            return manifest
        source = task_snapshot["baseline"] if task_snapshot else (self.root / "examples/todo/todo.py").read_text(encoding="utf-8")
        candidate.mkdir(parents=True, exist_ok=True)
        (candidate / "todo.py").write_text(source, encoding="utf-8")
        (directory / "baseline.py.txt").write_text(source, encoding="utf-8")
        manifest = {"workspace": str(candidate), "base_hash": hashlib.sha256(source.encode()).hexdigest()}
        if task_snapshot:
            trusted = directory / "trusted"
            trusted.mkdir()
            (trusted / "test_todo.py").write_text(task_snapshot["acceptance"], encoding="utf-8", newline="\n")
            (trusted / "requirement.md").write_text(task_snapshot["requirement"], encoding="utf-8", newline="\n")
            manifest.update(task_id=task_snapshot["id"], task_snapshot_sha256=task_snapshot["snapshot_sha256"],
                            target_relative=task_snapshot["paths"]["baseline"],
                            task=public_task(task_snapshot), acceptance_sha256=task_snapshot["acceptance_sha256"],
                            requirement_sha256=task_snapshot["requirement_sha256"], runner_manifest=self._acceptance_manifest())
        (directory / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8")
        return manifest

    async def read_project(self, run_id=None):
        path = self._run_dir(run_id) / "candidate/todo.py" if run_id else self.root / "examples/todo/todo.py"
        if path.is_symlink():
            raise RuntimeErrorSafe("Symlink source rejected")
        return {"files": [{"path": "todo.py", "content": path.read_text(encoding="utf-8")}]}

    async def retrieve(self, query, run_id=None):
        terms = set(re.findall(r"[a-z_]{2,}|[\u4e00-\u9fff]", str(query).lower()))
        matches = []
        for path in sorted((self.root / "knowledge").glob("*.md")):
            text = path.read_text(encoding="utf-8")
            score = sum(1 for term in terms if term in text.lower())
            matches.append({"path": "knowledge/" + path.name, "excerpt": text[:5000], "score": score})
        ranked = sorted(matches, key=lambda x: (-x["score"], x["path"]))[:3]
        if run_id:
            manifest_path = self._run_dir(run_id) / "manifest.json"
            if manifest_path.exists():
                manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
                if manifest.get("task"):
                    task = manifest["task"]
                    ranked = [{"path": task["paths"]["requirement"], "excerpt": task["requirement"],
                               "score": 10000, "sha256": task["requirement_sha256"], "source": "frozen_task_contract"},
                              *[item for item in ranked if item["path"] != "knowledge/requirements.md"]][:3]
        return {"matches": ranked, "method": "local_keyword"}

    def _post(self, payload):
        global _last_request_started
        key = self.settings["api_key"]
        if not key:
            raise RuntimeErrorSafe("未配置服务端模型密钥；真实模式无法启动。")
        url = self.settings["base_url"] + "/chat/completions"
        if not url.startswith("https://"):
            raise RuntimeErrorSafe("真实模型接口必须使用 HTTPS。")
        request = urllib.request.Request(url, data=json.dumps(payload).encode(), headers={"Content-Type": "application/json", "Authorization": "Bearer " + key})
        # Refuse redirects to avoid forwarding credentials to another origin.
        class NoRedirect(urllib.request.HTTPRedirectHandler):
            def redirect_request(self, *args, **kwargs):
                return None
        try:
            # One process-wide start limiter also covers parallel review/test
            # calls. Waiting here does not block the FastAPI event loop.
            interval = self.settings.get("min_request_interval", 0.0)
            if interval:
                with _request_lock:
                    delay = _last_request_started + interval - time.monotonic()
                    if delay > 0:
                        time.sleep(delay)
                    _last_request_started = time.monotonic()
            with urllib.request.build_opener(NoRedirect()).open(request, timeout=self.settings["timeout"]) as response:
                raw = response.read(524289)
                if len(raw) > 524288:
                    raise RuntimeErrorSafe("Model response exceeds size limit")
                return json.loads(raw)
        except urllib.error.HTTPError as exc:
            if exc.code >= 500:
                raise RuntimeErrorSafe(f"模型 HTTP {exc.code}；平台模型服务暂不可用，请核查服务渠道状态后重试。") from None
            if exc.code == 429:
                raise RuntimeErrorSafe("模型 HTTP 429；请求限流或额度限制，请核查平台限制后再恢复。") from None
            raise RuntimeErrorSafe(f"模型 HTTP {exc.code}；检查服务开通、模型 ID、额度和权限。") from None
        except (urllib.error.URLError, TimeoutError, OSError):
            raise RuntimeErrorSafe("模型网络请求失败或超时；可稍后恢复。") from None
        except json.JSONDecodeError:
            raise RuntimeErrorSafe("模型接口没有返回有效 JSON。") from None

    async def invoke(self, agent, task, context):
        metrics = {"model_calls": 0, "tokens": 0, "tool_calls": [], "metrics_complete": True,
                   "model_diagnostics": [], "contract_retries": 0}
        try:
            return await self._invoke_impl(agent, task, context, metrics)
        except asyncio.CancelledError as exc:
            # A cancelled to_thread HTTP request may still finish remotely.
            # Keep known usage and attempts; do not claim unknown usage is zero.
            for key, value in metrics.items():
                setattr(exc, key, value)
            raise
        except Exception as exc:
            safe = exc if isinstance(exc, RuntimeErrorSafe) else RuntimeErrorSafe(f"模型协议或输出处理失败：{type(exc).__name__}")
            for key, value in metrics.items():
                setattr(safe, key, value)
            raise safe from None

    async def _invoke_impl(self, agent, task, context, metrics):
        started = time.monotonic()
        role = agent.get("role", "reviewer")
